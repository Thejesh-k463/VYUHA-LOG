import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { PLATFORM_IDS, startHere } from "../scripts/lib/client-package.mjs";

/**
 * Owner rulings 2026-11-19: macOS is "Sold openly now" (replacing DECISIONS
 * 2026-09-06 Q65b and the 2026-08-15 decision that kept macOS off every selling
 * surface), under the "Same licence + price" as Windows, shipped as its own
 * client package. The old guard BANNED the word macOS from the demo copy and the
 * Import Help cards; this one requires the opposite on every surface that states
 * a platform:
 *
 *  1. it names Windows AND macOS;
 *  2. no current-tense sentence says there is no macOS build, "Windows only",
 *     "macOS is not sold" or "not on sale";
 *  3. wherever it tells a buyer to install on a Mac, the Gatekeeper sentence is
 *     there too — the Mac app is NOT signed or notarised by Apple, and the first
 *     open needs "Open Anyway" (the same honesty as the Windows SmartScreen line);
 *  4. it never claims the app is notarised or signed by Apple.
 *
 * Past release notes keep their own words (a release that shipped Windows-only
 * said so), so the client README is read up to its SECOND "## New in" heading —
 * the current release only — and README.md's top block plus its "Get it" section.
 */

const ROOT = path.resolve(__dirname, "..");
const decode = (s: string) => s.replace(/&amp;/g, "&").replace(/&nbsp;/g, " ").replace(/&#183;|&middot;/g, "·");
const read = (rel: string) => decode(fs.readFileSync(path.join(ROOT, rel), "utf8").replace(/\r\n/g, "\n"));

/** The client README's current section: everything before the second "## New in". */
function clientReadmeCurrent(): string {
  const t = read("docs/client/README.md");
  const heads = [...t.matchAll(/^## New in /gm)].map((m) => m.index!);
  expect(heads.length, "docs/client/README.md has fewer than two 'New in' sections").toBeGreaterThanOrEqual(2);
  return t.slice(0, heads[1]);
}

/** README.md: the top (badges + the current release's block) and the "Get it" section. */
function readmeCurrent(): string {
  const t = read("README.md");
  const blocks = [...t.matchAll(/^> \*\*v\d+\.\d+\.\d+ —/gm)].map((m) => m.index!);
  expect(blocks.length, "README.md has fewer than two release blocks").toBeGreaterThanOrEqual(2);
  const getIt = t.indexOf("## 🚀 Get it");
  expect(getIt, "README.md lost its Get it section").toBeGreaterThan(0);
  const end = t.indexOf("\n## ", getIt + 5);
  return `${t.slice(0, blocks[1])}\n${t.slice(getIt, end < 0 ? undefined : end)}`;
}

const SURFACES: { name: string; text: () => string }[] = [
  { name: "docs/sales/landing-page.html", text: () => read("docs/sales/landing-page.html") },
  { name: "docs/sales/brochure.html", text: () => read("docs/sales/brochure.html") },
  { name: "docs/index.html", text: () => read("docs/index.html") },
  { name: "docs/about.html", text: () => read("docs/about.html") },
  { name: "docs/client/README.md (current section)", text: clientReadmeCurrent },
  { name: "docs/client/INSTALLATION_GUIDE.md", text: () => read("docs/client/INSTALLATION_GUIDE.md") },
  { name: "docs/client/GETTING_STARTED_DECK.html", text: () => read("docs/client/GETTING_STARTED_DECK.html") },
  { name: "README.md (top + Get it)", text: readmeCurrent },
  { name: "docs/owner/CREATOR_KIT.md", text: () => read("docs/owner/CREATOR_KIT.md") },
  ...(PLATFORM_IDS as string[]).map((platform) => ({
    name: `START_HERE.md (${platform})`,
    text: () => startHere({ version: "4.7.0", platform }),
  })),
  // Generated by scripts/build-landing.mjs and .gitignore(d): scanned when present,
  // so a stale emailable copy cannot say what the source no longer does. Absent on
  // a fresh clone, where it falls back to its source so the test count is stable.
  {
    name: "docs/sales/landing-page.standalone.html (or its source when not built)",
    text: () =>
      read(
        fs.existsSync(path.join(ROOT, "docs/sales/landing-page.standalone.html"))
          ? "docs/sales/landing-page.standalone.html"
          : "docs/sales/landing-page.html",
      ),
  },
];

/** Current-tense phrasing the 2026-11-19 ruling retired. */
const RETIRED: RegExp[] = [
  /\bWindows[- ]only\b/i,
  /\bWindows 10\/11 64-bit only\b/i,
  /\bno macOS build\b/i,
  /\bmacOS (is|isn't|is not) (sold|supported)\b/i,
  /\bnot (sold|on sale)\b[^.]{0,40}\bmac/i,
  /\bmac[^.]{0,40}\bnot (sold|on sale)\b/i,
  /\bnot on sale\b/i,
];

/** A sentence that tells someone to install / open the app on a Mac. */
const MAC_INSTALL = /drag(s|ging)? Vyuha (in)?to (the )?Applications|\.dmg\b|install(ed|ing)? (it )?on a Mac/i;
const GATEKEEPER = /Open Anyway/;

/** "notarised" / "signed by Apple" must sit in a negated clause. */
function unnegatedAppleClaims(text: string): string[] {
  const out: string[] = [];
  for (const m of text.matchAll(/notari[sz](ed|ation)|signed by Apple|Apple[- ]signed/gi)) {
    const before = text.slice(Math.max(0, m.index! - 90), m.index!);
    const clause = before.split(/[.!?]\s|\n\n/).pop() ?? "";
    if (!/\b(not|no|never|neither|nor|without|isn't|is not)\b/i.test(clause)) out.push(`…${clause}${m[0]}`);
  }
  return out;
}

describe("every surface that states a platform says Windows AND macOS (owner ruling 2026-11-19)", () => {
  for (const s of SURFACES) {
    describe(s.name, () => {
      it("names Windows and macOS", () => {
        const t = s.text();
        expect(t, `${s.name} does not name Windows`).toMatch(/\bWindows\b/);
        expect(t, `${s.name} does not name macOS`).toMatch(/\bmacOS\b/);
      });

      it("carries no retired 'no macOS' / 'Windows only' phrasing", () => {
        const t = s.text();
        const found = RETIRED.map((re) => re.exec(t)?.[0]).filter(Boolean);
        expect(found, `${s.name} still says: ${found.join(" | ")}`).toEqual([]);
      });

      it("pairs any Mac install instruction with the Open Anyway sentence", () => {
        const t = s.text();
        if (MAC_INSTALL.test(t)) expect(t, `${s.name} tells a buyer to install on a Mac without the Gatekeeper step`).toMatch(GATEKEEPER);
      });

      it("never claims the Mac app is notarised or signed by Apple", () => {
        expect(unnegatedAppleClaims(s.text())).toEqual([]);
      });
    });
  }
});

describe("the retired bans are gone", () => {
  it("neither copy test bans the word macOS any more", () => {
    for (const f of ["tests/demo-video-copy.test.ts", "tests/import-help-content.test.ts"]) {
      expect(fs.readFileSync(path.join(ROOT, f), "utf8"), f).not.toMatch(/macOS is not sold \(owner decision/);
    }
  });

  it("the Gatekeeper and notarisation checks catch what they are for", () => {
    // Self-test, so a regex edit cannot quietly make the guard pass everything.
    expect(unnegatedAppleClaims("The Mac app is notarised by Apple.")).toHaveLength(1);
    expect(unnegatedAppleClaims("The Mac app is not signed or notarised by Apple.")).toEqual([]);
    expect(MAC_INSTALL.test("Open the .dmg and drag Vyuha into Applications.")).toBe(true);
    expect(RETIRED.some((re) => re.test("There is no macOS build — Windows only."))).toBe(true);
  });
});
